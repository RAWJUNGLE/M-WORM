#!/usr/bin/env python3
"""Generate mworm/worm/font6x8.h from Press Start 2P (SIL OFL 1.1).

Press Start 2P is a monospaced 8x8 pixel font: every glyph is 8px advance,
8px tall, drawn pixel-perfect (no anti-aliasing) at 8px. This renders ASCII
32..126 into 8-byte rows (one byte per row, bit7 = left pixel), to replace the
original 6x8 DejaVu font (the worm UI's text() advances 8*z px instead of 6*z).

Usage: .venv/bin/python make_font6x8.py
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONT = os.path.expanduser("~/Library/Fonts/PressStart2P-Regular.ttf")
OUT = os.path.join(HERE, "font6x8.h")

f = ImageFont.truetype(FONT, 8)

o = ["/* generated by make_font6x8.py: Press Start 2P (SIL OFL 1.1), 8x8, bit7=left */",
     "static const unsigned char worm_font6x8[95][8]={"]
for c in range(32, 127):
    im = Image.new("L", (8, 8), 0)
    ImageDraw.Draw(im).text((0, 0), chr(c), font=f, fill=255)
    rows = []
    for y in range(8):
        b = 0
        for x in range(8):
            b = (b << 1) | (1 if im.getpixel((x, y)) > 110 else 0)
        rows.append(b)
    o.append("{" + ",".join("0x%02X" % r for r in rows) + "},")
o.append("};")
open(OUT, "w").write("\n".join(o) + "\n")
print("wrote", OUT)
