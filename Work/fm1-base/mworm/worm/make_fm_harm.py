#!/usr/bin/env python3
"""Generates worm_fm_harm.h: 27 key frames of the FM HARM parameter (additive series, 11 partials, one period = 128 points).
Order as in the Digitone manual (appendix A.6): 0 sine, 1-7 saw (all partials, growing), 8-14 saw reduction down to the odd/even mix,
15-19 square (odd partials, growing), 20-23 square reduction, 24-26 bell. Own implementation, no tables copied."""
import math
K=11
def frame(h):
    a=[0.0]*(K+1)           # a[k], k=1..K
    if h==0: a[1]=1
    elif h<=7:               # saw: partials 1..h+1, 1/k
        for k in range(1,h+2): a[k]=1.0/k
    elif h<=14:              # saw reduction: even partials fade 1 -> .25, top partials thin out
        f=1-(h-7)*0.75/7
        for k in range(1,9): a[k]=(1.0/k)*(1 if k&1 else f)
    elif h<=19:              # square: odd partials 1,3,..2j+1
        j=h-14
        for k in range(1,2*j+2,2): a[k]=1.0/k
    elif h<=23:              # square reduction: 3rd and 5th partial pulled out, 7th/9th pushed in
        j=h-19
        for k in (1,3,5,7,9): a[k]=1.0/k
        a[3]*=1-0.22*j; a[5]*=1-0.15*j; a[7]*=1+0.25*j; a[9]*=1+0.3*j
    else:                    # bell
        b=h-23
        if b==1: a[1]=1;a[3]=.45;a[7]=.15
        elif b==2: a[1]=1;a[4]=.4;a[6]=.3;a[9]=.1
        else: a[1]=1;a[3]=.2;a[5]=.35;a[8]=.35
    return a
out=[]
for h in range(27):
    a=frame(h)
    w=[sum(a[k]*math.sin(2*math.pi*k*i/128) for k in range(1,K+1)) for i in range(128)]
    pk=max(abs(x) for x in w) or 1
    out.append([int(round(x/pk*0.95*32767)) for x in w])
with open('worm_fm_harm.h','w') as f:
    f.write('/* generated by make_fm_harm.py: FM HARM key frames, 27 x 128 x int16 (flash) */\n')
    f.write('const int16_t worm_fm_harm[FM_NH][128]={\n')
    for fr in out:
        f.write('{'+','.join(str(x) for x in fr)+'},\n')
    f.write('};\n')
