#!/usr/bin/env python3
"""Generate the 5 MAIN wavetables (all 64 frames) for M-WORM.

  python3 tools/gen_wt_main.py [tables_dir]            # default: tables_src/ next to tools/

Writes
  mworm/worm/worm_wt_main.c     const int16_t worm_wt_main[5][64][256]   (firmware)
  mworm/web/wt_main.json        the same data as base64 (the web tool embeds it)

Per-frame clean-up, so that scanning POS does not thump:
  * DC removed from every frame (PWN_SAW is unipolar in the source: its DC walks from -1 to 0);
  * every frame scaled to the same RMS (limited by peak), so loudness stays level along the table;
  * a silent first frame (MELLOW_D) is replaced by a sine.
"""
import base64, json, math, pathlib, struct, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
TABLES = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "tables_src"
OUT_C = ROOT / "mworm" / "worm" / "worm_wt_main.c"
OUT_J = ROOT / "mworm" / "web" / "wt_main.json"

# (file, short name <= 5 chars shown on the screen, long name for the tool)
MAIN = [
    ("PWN_SAW",  "PWN",   "PWN SAW · pulse → saw"),
    ("PPG_WA28", "PPG",   "PPG WAVE 2.8"),
    ("VIRUS_SA", "VIRUS", "VIRUS SAW stack"),
    ("VOCAL_00", "VOCAL", "VOCAL formants"),
    ("MELLOW_D", "MELLO", "MELLOW · sine → bright"),
]
TARGET_RMS = 13000.0
PEAK_LIM = 31500.0
NF, N = 64, 256


def load(name):
    b = (TABLES / (name + ".WAV")).read_bytes()
    assert b[:4] == b"RIFF" and b[8:12] == b"WAVE"
    off, data = 12, None
    while off + 8 <= len(b):
        cid, ln = b[off:off + 4], struct.unpack("<I", b[off + 4:off + 8])[0]
        if cid == b"data":
            data = b[off + 8:off + 8 + ln]
        off += 8 + ln + (ln & 1)
    s = struct.unpack("<%dh" % (len(data) // 2), data)
    assert len(s) >= NF * N, name
    return [list(s[i * N:(i + 1) * N]) for i in range(NF)]


def clean(frames):
    out = []
    for fr in frames:
        dc = sum(fr) / N
        x = [v - dc for v in fr]
        rms = math.sqrt(sum(v * v for v in x) / N)
        if rms < 50:                                   # silent frame: pure sine
            x = [math.sin(2 * math.pi * i / N) for i in range(N)]
            rms = math.sqrt(sum(v * v for v in x) / N)
        pk = max(abs(v) for v in x)
        k = min(TARGET_RMS / rms, PEAK_LIM / pk)
        out.append([max(-32768, min(32767, int(round(v * k)))) for v in x])
    return out


def main():
    tabs = [clean(load(f)) for f, _, _ in MAIN]
    lines = [
        "/* MAIN wavetables: 5 tables x 64 frames x 256 int16. GENERATED by tools/gen_wt_main.py from tables_src/*.WAV",
        " * (DC removed, every frame at the same RMS). Frame index = POS * 63 / 127; the oscillator morphs between neighbouring frames. */",
        "#include <stdint.h>",
        "#include \"worm_wt.h\"",
        "",
        "const int16_t worm_wt_main[WT_MAIN][WT_FRAMES][WT_N] = {",
    ]
    for (f, short, _), t in zip(MAIN, tabs):
        lines.append(" { /* %s */" % f)
        for i, fr in enumerate(t):
            lines.append("  { /* %d */" % i)
            for j in range(0, N, 16):
                lines.append("   " + ",".join("%d" % v for v in fr[j:j + 16]) + ",")
            lines.append("  },")
        lines.append(" },")
    lines.append("};")
    OUT_C.write_text("\n".join(lines) + "\n", encoding="utf-8")
    js = []
    for (f, short, long), t in zip(MAIN, tabs):
        raw = b"".join(struct.pack("<%dh" % N, *fr) for fr in t)
        js.append({"file": f, "short": short, "name": long, "b64": base64.b64encode(raw).decode()})
    OUT_J.parent.mkdir(parents=True, exist_ok=True)
    OUT_J.write_text(json.dumps(js, separators=(",", ":")), encoding="utf-8")
    print("wrote", OUT_C, OUT_C.stat().st_size, "bytes;", OUT_J, OUT_J.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
