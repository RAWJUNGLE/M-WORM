#!/usr/bin/env python3
"""Generate mworm/worm/worm_wt_data.c from Work/tables/*.WAV.

Cycle 0 of each file, 256 int16 samples, peak-normalised to 32767. The first
eight tables keep their historical order so saved WAVE values stay compatible;
the rest are appended alphabetically.
"""
import pathlib
import struct
import wave

FIRST = ["SINE_SPE", "PPG_WA28", "PROPHET_", "PWN_SAW", "MORPHING", "VIRUS_SA", "SYNLP10", "SPECTR00"]
ROOT = pathlib.Path(__file__).resolve().parents[2]
TABLES = ROOT / "tables"
OUT = pathlib.Path(__file__).resolve().parents[1] / "mworm" / "worm" / "worm_wt_data.c"


def load(name):
    with wave.open(str(TABLES / (name + ".WAV")), "rb") as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2, name
        assert w.getframerate() == 44100 and w.getnframes() >= 256, name
        raw = w.readframes(256)
    samples = struct.unpack("<256h", raw)
    peak = max(abs(x) for x in samples)
    # Exactly the tool's library rule: cycle 0, peak-normalised; a silent
    # cycle (MELLOW_D, QUACK) stays silent. Keep firmware bit-identical to
    # the WAV data embedded in mworm_tool_*.html.
    if peak == 0:
        return list(samples)
    return [max(-32768, min(32767, round(x * 32767 / peak))) for x in samples]


def main():
    names = [p.stem for p in TABLES.glob("*.WAV")]
    assert len(names) == 40, f"expected 40 WAV files, got {len(names)}"
    names.sort()
    order = FIRST + [n for n in names if n not in FIRST]
    assert len(order) == len(set(order)) == 40
    lines = [
        "/* Built-in wavetables: cycle 0 of Work/tables WAV files, 256 int16 each, peak-normalised.",
        " * Generated by tools/gen_wt_data.py; the first eight keep their original order. */",
        "#include <stdint.h>",
        "",
        f"const int16_t worm_wt_builtin[{len(order)}][256] = {{",
    ]
    for name in order:
        data = load(name)
        lines.append(f" /* {name} */ {{")
        for i in range(0, 256, 16):
            lines.append("    " + ", ".join(f"{x:6d}" for x in data[i:i + 16]) + ",")
        lines.append(" },")
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}: {len(order)} x 256 int16")


if __name__ == "__main__":
    main()
